def plural(n, one, few, many):
    """Russian plural agreement: 1 страница / 2 страницы / 5 страниц."""
    n = abs(int(n))
    if n % 100 in range(11, 15):
        return many
    return {1: one, 2: few, 3: few, 4: few}.get(n % 10, many)


